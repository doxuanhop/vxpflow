/** Phát hiện ngôn ngữ hệ thống — trả ngôn ngữ hỗ trợ khớp, ngược lại ENGLISH
 *  (chỉ dùng làm tiện ích; mặc định khởi động luôn là English) */
export function detectSystemLang(): Lang {
  try {
    const nav = (navigator.language || 'en').toLowerCase();
    for (const { code } of SUPPORTED_LANGS) {
      if (nav.startsWith(code)) return code;
    }
    return 'en';
  } catch {
    return 'en';
  }
}

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY) as Lang | null;
    if (saved && SUPPORTED_LANGS.some(l => l.code === saved)) return saved;
  } catch { /* ignore */ }
  // Mặc định English — người dùng đổi qua LanguageSwitcher khi muốn
  return 'en';
}

/* ---------------- React context ---------------- */

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nCtx>({
  lang: 'en',
  setLang: () => {},
  t: (k, f) => f ?? k,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nCtx>(() => ({
    lang,
    setLang: setLangState,
    t: (key, fallback) => DICTS[lang][key] ?? EN[key] ?? fallback ?? key,
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nCtx {
  return useContext(I18nContext);
}

/** Chọn ngôn ngữ — dropdown trong Navbar (13 ngôn ngữ) */
export const LanguageSwitcher: React.FC = () => {
  const { lang, setLang } = useI18n();
  const [open, setOpen] = useState(false);
  const cur = SUPPORTED_LANGS.find(l => l.code === lang) || SUPPORTED_LANGS[0];

  useEffect(() => {
    if (!open) return;
    const close = () => setOpen(false);
    window.addEventListener('click', close);
    return () => window.removeEventListener('click', close);
  }, [open]);

  return (
    <div className="relative shrink-0" onClick={(e) => e.stopPropagation()}>
      <button
        onClick={(e) => { e.stopPropagation(); setOpen(o => !o); }}
        className="px-2 py-1 rounded-lg border border-[#E4DEF1] bg-[#F7F3FC] hover:bg-[#F3EEFA] text-[#494256] hover:text-[#221E2B] text-[11px] font-semibold transition-colors cursor-pointer flex items-center gap-1"
        title={`${cur.label} — ${cur.code.toUpperCase()}`}
      >
        <span>{cur.flag}</span>
        <span className="hidden sm:inline">{cur.code.toUpperCase()}</span>
        <span className="text-[8px]">▾</span>
      </button>
      {open && (
        <div className="absolute right-0 top-full mt-1 bg-[#F7F3FC] border border-[#CBC3DD] rounded-lg shadow-2xl py-1 z-[80] min-w-[170px] max-h-[320px] overflow-y-auto">
          {SUPPORTED_LANGS.map(l => (
            <button
              key={l.code}
              onClick={(e) => { e.stopPropagation(); setLang(l.code); setOpen(false); }}
              className={`w-full text-left px-3 py-1.5 text-[11px] flex items-center gap-2 transition-colors cursor-pointer ${
                l.code === lang ? 'bg-[#6750A4] text-white font-bold' : 'text-[#221E2B] hover:bg-[#F3EEFA]'
              }`}
            >
              <span>{l.flag}</span>
              <span className="flex-1 truncate">{l.label}</span>
              {l.code === lang && <span className="text-[9px]">✓</span>}
            </button>
          ))}
        </div>
      )}
    </div>
  );
};
